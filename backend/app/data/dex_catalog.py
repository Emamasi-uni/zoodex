def get_dex_entry_for_class(cls_name: str, cls_id: int = 0) -> Dict[str, Any]:
    """Returns a rich Pokédex entry for any recognized class."""
    clean_name = cls_name.lower().strip()
    if clean_name in COCO_TRANSLATIONS:
        name, sci_name, cat, is_anim, cont_id, cont_name, rarity, h, w, desc, color = COCO_TRANSLATIONS[clean_name]
        return {
            "dex_number": f"{cls_id + 1:03d}" if is_anim else f"OBJ-{cls_id:02d}",
            "name": name,
            "scientific_name": sci_name,
            "continent": cont_id,
            "continent_name": cont_name,
            "category": cat,
            "is_animal": is_anim,
            "rarity": rarity,
            "height": h,
            "weight": w,
            "description": desc,
            "badge_color": color,
        }

    # Open-Vocabulary fallback for any unlisted object or wild species
    is_likely_animal = any(term in clean_name for term in [
        "animal", "bird", "fish", "dog", "cat", "bear", "fox", "wolf", "deer", "lion", "tiger",
        "snake", "lizard", "monkey", "eagle", "frog", "whale", "shark", "insect", "spider"
    ])

    return {
        "dex_number": f"EXP-{cls_id:03d}",
        "name": clean_name.replace("_", " ").title(),
        "scientific_name": f"Specimen {clean_name}",
        "continent": "europa",
        "continent_name": "Globale" if not is_likely_animal else "Fauna Esterna",
        "category": "Fauna Non Catalogata" if is_likely_animal else "Oggetto Rilevato",
        "is_animal": is_likely_animal,
        "rarity": "Rilevato",
        "height": "Variabile",
        "weight": "In analisi",
        "description": f"Entità rilevata dai sensori ottici ad alta sensibilità dello Zoodex: {clean_name}.",
        "badge_color": "#00E5FF" if is_likely_animal else "#94A3B8",
    }

